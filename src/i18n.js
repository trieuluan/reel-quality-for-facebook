  // Facebook's <html lang> follows the account's language (e.g. "pt", "zh-Hant", "tl"); fall back to the browser's.
  function lang() {
    const tag = (document.documentElement.lang || navigator.language || 'en').toLowerCase();
    if (tag.startsWith('zh')) return /hant|tw|hk|mo/.test(tag) ? 'zh_TW' : 'zh_CN';
    if (tag.startsWith('tl') || tag.startsWith('fil')) return 'fil';
    const base = tag.split(/[-_]/)[0];
    return STRINGS[base] ? base : 'en';
  }

  FBQ.i18n = {
    lang,
    t: (key) => STRINGS[lang()][key] ?? STRINGS.en[key],
    rtl: () => lang() === 'ar',
  };

  // Times and dates come from the browser's Intl, so they need no translations of their own.
  const locale = (code) => code.replace('_', '-');
  const MINUTE = 60_000;
  const HOUR = 60 * MINUTE;
  const DAY = 24 * HOUR;
  const midnight = (ts) => new Date(ts).setHours(0, 0, 0, 0);
  FBQ.fmt = {
    // "5 minutes ago", "yesterday", "3 days ago", then a date.
    ago(ts, code = lang()) {
      const rtf = new Intl.RelativeTimeFormat(locale(code), { numeric: 'auto' });
      const diff = Date.now() - ts;
      if (diff < HOUR) return rtf.format(-Math.max(1, Math.floor(diff / MINUTE)), 'minute'); // "1 minute ago" rather than "now"
      if (diff < DAY && midnight(ts) === midnight(Date.now())) return rtf.format(-Math.floor(diff / HOUR), 'hour');
      const days = Math.round((midnight(Date.now()) - midnight(ts)) / DAY);
      if (days >= 7) return FBQ.fmt.date(ts, code);
      // "yesterday" by name, then "3 days ago" rather than words like "the day before yesterday"; lower case, since it
      // goes inside a sentence ("Watched yesterday"), except in German where nouns keep their capital.
      const word = days < 2 ? rtf.format(-days, 'day') : new Intl.RelativeTimeFormat(locale(code), { numeric: 'always' }).format(-days, 'day');
      return code === 'de' ? word : word.charAt(0).toLocaleLowerCase(locale(code)) + word.slice(1);
    },
    date(ts, code = lang()) {
      const sameYear = new Date(ts).getFullYear() === new Date().getFullYear();
      return new Intl.DateTimeFormat(locale(code), { day: 'numeric', month: 'short', year: sameYear ? undefined : 'numeric' }).format(ts);
    },
    // "Today", "Yesterday", or a full date with the weekday: the headings of the library's day groups.
    day(ts, code = lang()) {
      const days = Math.round((midnight(Date.now()) - midnight(ts)) / DAY);
      if (days < 2) {
        const word = new Intl.RelativeTimeFormat(locale(code), { numeric: 'auto' }).format(-days, 'day');
        return word.charAt(0).toLocaleUpperCase(locale(code)) + word.slice(1);
      }
      const sameYear = new Date(ts).getFullYear() === new Date().getFullYear();
      return new Intl.DateTimeFormat(locale(code), { weekday: 'long', day: 'numeric', month: 'long', year: sameYear ? undefined : 'numeric' }).format(ts);
    },
    // m:ss, or h:mm:ss for an hour or more.
    clock(t, hours = t >= 3600) {
      const s = Math.max(0, Math.floor(t));
      const pad = (n) => String(n).padStart(2, '0');
      return hours ? `${Math.floor(s / 3600)}:${pad(Math.floor(s / 60) % 60)}:${pad(s % 60)}` : `${Math.floor(s / 60)}:${pad(s % 60)}`;
    },
  };
